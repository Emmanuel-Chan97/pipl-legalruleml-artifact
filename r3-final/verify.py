"""Acceptance tests over the editable R3 JSON, the exporter CLI and the emitted XML."""
import argparse
from collections import Counter
from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory

from lxml import etree

from qa import profile
import qa_previous_round as prior
from storage import for_export, to_round_two


ROOT = Path(__file__).resolve().parent
EXPORT = ROOT / "exporter" / "export_native.py"
R2_HASH = "eeae5c9d4d25f5c3f548d7e5d9755710b61a32a769bfd3b24b03943225eee0d5"
FULL_HASH = "afb46927f50901c124b825e566a3365816324b3813188a12a74624aa07b5e40b"
XML_HASH = "1c3389f64e8f0a9b20f79776e21ef056a20da7cf45eb8c268c279c9cfac42e8d"
CATEGORIES = {
    "义务": 103, "适用与定义": 25, "权利": 19, "监管权限": 19, "禁止": 18,
    "法律责任": 10, "许可与豁免": 5, "制度与立法背景": 3, "原则背景": 3,
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_json(path):
    return json.loads(path.read_bytes())


def digest(value):
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return sha256(encoded).hexdigest()


def record(model, record_id):
    return next(item for item in model["records"] if item["id"] == record_id)


def waiver(model):
    return next(item for item in model["exceptions"] if item["id"] == "E57-PERSON-WAIVER")


def check_views(model, baseline):
    restored = to_round_two(model)
    require(digest(restored) == R2_HASH, "Restored R2 release fingerprint changed")
    require(digest(for_export(model)) == FULL_HASH, "Restored full record fingerprint changed")
    if baseline is not None:
        require(restored == read_json(baseline), "Restored data differs from supplied R2 baseline")
    rows = restored["records"]
    require(Counter(r["category"] for r in rows) == CATEGORIES, "Chinese display classification changed")
    duties = Counter(r["category"] for r in rows if r["legalruleml"].get("native_element") == "lrml:Obligation")
    require(duties == {"义务": 103, "监管权限": 5, "法律责任": 2}, "Obligation was conflated with a display category")
    require(all("category" not in r for r in model["records"]), "Records duplicate their display category")
    for key, expected in (("61.4", "义务"), ("66.1a", "监管权限")):
        r = record(restored, key)
        require(r["category"] == expected and r["rule_function"] == "statutory_duty"
                and r["legalruleml"].get("native_element") == "lrml:Obligation", f"{key}: lost independent display classification")
    print("PASS  Complete R2 and expanded data, nine display categories, 110 distinct Obligation classifications")


def set_joint_disposal(model):
    record(model, "21.2c")["content_expr"]["op"] = "all"


def misdirect_waiver(model):
    waiver(model)["target_ids"] = ["57.1b"]


def condition_proactive_deletion_on_request(model):
    row = record(model, "47.1a")
    row["activation"] = {
        "op": "all",
        "args": [row["activation"], {"op": "predicate", "text": "个人提出删除请求"}],
    }


def exclude_security_only(model):
    # Omitting storage from the carve-out would prohibit storage as well.
    record(model, "47.2")["content_expr"]["object"] = "除采取必要安全保护措施之外的个人信息处理活动"


def export(source_path, output):
    return subprocess.run([sys.executable, str(EXPORT), str(source_path), str(output)],
                          capture_output=True, text=True)


def write_input(path, model):
    path.write_text(json.dumps(model, ensure_ascii=False), encoding="utf-8")


def check_entry_points(model, source):
    schema = profile.schema()
    with TemporaryDirectory() as temp:
        work = Path(temp)
        out = work / "rules.lrml"
        mutated = work / "variant.json"
        result = export(source, out)
        require(result.returncode == 0, result.stdout + result.stderr)
        original = out.read_bytes()
        require(sha256(original).hexdigest() == XML_HASH, "Export differs from the R2 XML baseline")
        require(original == (ROOT / model["interchange"]["file"]).read_bytes(), "Bundled XML differs from export")
        doc = etree.parse(out, etree.XMLParser(no_network=True, resolve_entities=False))
        schema.assertValid(doc)
        problems = profile.check_links(doc) + profile.check_pilot(doc)
        require(not problems, repr(problems))
        print("PASS  Released XML regenerated byte-for-byte, Compact XSD, references and pilot checks")

        variants = (
            (set_joint_disposal, ("21.2c", "content_expr")),
            (misdirect_waiver, ("E57-PERSON-WAIVER", "target_ids")),
            (condition_proactive_deletion_on_request, ("47.1a", "activation")),
            (exclude_security_only, ("47.2", "content_expr")),
        )
        def move_time_to_regulator(data):
            record(data, "57.1a")["temporal"][0]["applies_to"] = "通知履行个人信息保护职责的部门"

        def reverse_right_holder(data):
            roles = record(data, "24.3a")["participants"]
            next(p for p in roles if p["role"] == "claim_holder")["label"] = "个人信息处理者"

        variants += (
            (move_time_to_regulator, ("57.1a", "temporal", "applies_to")),
            (reverse_right_holder, ("24.3a", "participants", "claim_holder")),
        )
        for alter, required_tokens in variants:
            changed = deepcopy(model)
            alter(changed)
            write_input(mutated, changed)
            result = export(mutated, out)
            diagnostic = result.stdout + result.stderr
            require(result.returncode != 0, f"{alter.__name__}: exporter accepted the edited source")
            require(all(token in diagnostic for token in required_tokens),
                    f"{alter.__name__}: missing source/field diagnostic in {diagnostic}")
            require(out.read_bytes() == original, f"{alter.__name__}: failed export replaced the previous output")
            print(f"PASS  Rejected {'.'.join(required_tokens)} at the exporter; previous output preserved")

        # A legitimate change must not be rejected by a whole-file fingerprint guard.
        edited = deepcopy(model)
        target = record(edited, "57.2a")["field_annotations"]["conduct_force"]
        target["note"] += "（独立审阅意见，仅用于本次验收。）"
        write_input(mutated, edited)
        result = export(mutated, out)
        require(result.returncode == 0, "Valid annotation edit rejected: " + result.stdout + result.stderr)
        schema.assertValid(etree.parse(out))
        print("PASS  A new editorial note is accepted through the same exporter")

        reordered = deepcopy(model)
        record(reordered, "21.2c")["content_expr"]["args"].reverse()
        write_input(mutated, reordered)
        result = export(mutated, out)
        require(result.returncode == 0, "Legally equivalent OR reordering rejected: " + result.stdout + result.stderr)
        schema.assertValid(etree.parse(out))
        print("PASS  Reordering alternatives in 21.2c is accepted")

        priorities = doc.xpath("//lrml:Override[@over='#r-57-2a']", namespaces=profile.NS)
        require(len(priorities) == 1, "Expected one Article 57 waiver priority")
        priorities[0].set("under", "#r-57-1b")
        schema.assertValid(doc)
        require(not profile.check_links(doc) and any("r-57-1c" in msg for msg in profile.check_pilot(doc)),
                "Independent XML-side checker missed the well-formed but wrong target")
        print("PASS  Direct XML wrong-target mutation passes XSD and is rejected by the legal pilot test")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline-r2", type=Path, help="Optional original round-two PIPL-model.json for deep equality")
    parser.add_argument("--baseline-r1", type=Path, help="Optional R1 data for checking the full provenance view")
    parser.add_argument("--baseline", type=Path, help="Optional expanded v4.1 role/label data")
    args = parser.parse_args()
    source = ROOT / "PIPL-model.json"
    model = read_json(source)
    check_views(model, args.baseline_r2)
    prior.check_new_storage(model)
    prior.check_restored_views(model, args.baseline_r1)
    prior.check_edit_propagation(model)
    if args.baseline:
        require(for_export(model) == read_json(args.baseline), "Expanded v4.1 data differs from supplied baseline")
    check_entry_points(model, source)


if __name__ == "__main__":
    main()
